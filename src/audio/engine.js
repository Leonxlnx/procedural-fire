// engine.js — main-thread API for the live procedural campfire audio.
//
//   import { FireAudio } from './src/audio/engine.js';
//   const a = await FireAudio.create();          // or FireAudio.create(existingCtx, { seed, volume, ... })
//   button.onclick = () => a.start();            // start() must run inside a user gesture (autoplay policy)
//   // every frame:
//   a.update({ intensity, hrr, dhrr, camDist, camAz });
//   // scripted events (sample-accurate, scheduled `scheduleAhead` s ahead):
//   a.trigger({ type: 'pop', strength: 0.8, pan: -0.2 });   // 'ignite'|'pop'|'crackle-burst'|'log-shift'|'whoosh'|'gust'
//   // random pops generated by the engine -> spark bursts in sync with the sound:
//   const off = a.onEvent((ev) => spawnSparks(ev));          // ev: { type, strength, size, pan, x, y, z, contextTime, time }
//   a.setVolume(0.8); a.stop(); a.resume();
//
// Graph: fire-audio worklet ─┬─ dry ──────────────────────────────┐
//                            └─ send ─ ConvolverNode (procedural  ├─ fire-master worklet (EQ, make-up, soft clip,
//                                      outdoor IR, true stereo)  ─┘   leveler, true-peak lookahead limiter @ -1 dBFS) ─ GainNode (volume) ─ destination
// Live loudness (default make-up 4.5 dB, leveler above -16 LUFS): about -18.5 LUFS at intensity 1 / 2.2 m, true peak
// <= -1.1 dBTP (tools/audio_analysis/live_level.mjs). The master delays the sound by ~3.2 ms (FIR band-limit,
// oversampled clip, limiter lookahead); onEvent()'s audible time `time` includes that delay, `contextTime` does not.
import { makeOutdoorIR, REVERB_DEFAULTS, EVENT_TYPES, decodeEvents, LiveMaster } from './fire-dsp.js';

const WORKLET_URL = new URL('./worklet.js', import.meta.url);
const modulePromises = new WeakMap();
const GESTURES = ['pointerdown', 'pointerup', 'keydown', 'touchend', 'mousedown'];

export class FireAudio {
  /**
   * @param {BaseAudioContext} [ctx]  existing (Offline)AudioContext; a new 48 kHz AudioContext is created when omitted.
   * @param {object} [options] { seed, params, controls, volume (0..1), makeupDb, ceilingDb, reverb, scheduleAhead, connect }
   */
  static async create(ctx, options = {}) {
    if (ctx && !(typeof BaseAudioContext !== 'undefined' && ctx instanceof BaseAudioContext)) { options = ctx; ctx = null; }
    const owned = !ctx;
    if (!ctx) ctx = new AudioContext({ sampleRate: options.sampleRate ?? 48000, latencyHint: options.latencyHint ?? 'interactive' });
    let p = modulePromises.get(ctx);
    if (!p) { p = ctx.audioWorklet.addModule(WORKLET_URL); modulePromises.set(ctx, p); }
    await p;
    return new FireAudio(ctx, owned, options);
  }

  constructor(ctx, owned, o = {}) {
    this.ctx = ctx;
    this.owned = owned;
    this.offline = typeof OfflineAudioContext !== 'undefined' && ctx instanceof OfflineAudioContext;
    this.seed = (o.seed ?? (Math.random() * 4294967296)) >>> 0;
    this.scheduleAhead = o.scheduleAhead ?? 0.03;
    this.volume = clamp01(o.volume ?? 1);
    this.started = false;
    this.meter = { peakDb: -Infinity, rmsDb: -Infinity, grDb: 0 };
    this.recentEvents = [];
    this._subs = new Set();
    this._ctl = { type: 'ctl' };
    this._lastHrr = null; this._lastHrrT = 0;
    this._gestureArmed = false;
    this._onGesture = () => { this.ctx.resume().catch(() => {}); if (this.ctx.state === 'running') this._disarmGesture(); };

    this.node = new AudioWorkletNode(ctx, 'fire-audio', {
      numberOfInputs: 0, numberOfOutputs: 2, outputChannelCount: [2, 2],
      // offline contexts render only on startRendering(), so they run from the first quantum (no message race)
      processorOptions: { seed: this.seed, params: o.params || {}, controls: o.controls || {}, running: this.offline },
    });
    const rv = { ...REVERB_DEFAULTS, ...(o.reverb || {}) };
    const [irL, irR] = makeOutdoorIR(ctx.sampleRate, this.seed, rv);
    const ir = ctx.createBuffer(4, irL.length, ctx.sampleRate); // true stereo: LL, LR, RL, RR (15 % cross-feed)
    const cf = rv.crossFeed ?? 0.15, xL = new Float32Array(irL.length), xR = new Float32Array(irR.length);
    for (let i = 0; i < irL.length; i++) { xL[i] = irL[i] * cf; xR[i] = irR[i] * cf; }
    ir.copyToChannel(irL, 0); ir.copyToChannel(xL, 1); ir.copyToChannel(xR, 2); ir.copyToChannel(irR, 3);
    this.reverb = new ConvolverNode(ctx, { buffer: ir, disableNormalization: true });
    this.master = new AudioWorkletNode(ctx, 'fire-master', {
      numberOfInputs: 1, numberOfOutputs: 1, outputChannelCount: [2], channelCount: 2, channelCountMode: 'explicit', channelInterpretation: 'speakers',
      processorOptions: { ceilingDb: o.ceilingDb ?? -1.0, makeupDb: o.makeupDb ?? 4.5, levelerThresholdLufs: o.levelerThresholdLufs ?? -16, releaseMs: 120, lookMs: 1.5 },
    });
    this.masterDelay = LiveMaster.latencySamples(ctx.sampleRate, 1.5) / ctx.sampleRate; // s, added to the audible time
    this.output = new GainNode(ctx, { gain: 0 });
    this.node.connect(this.master, 0, 0);
    this.node.connect(this.reverb, 1, 0);
    this.reverb.connect(this.master);
    this.master.connect(this.output);
    if (o.connect !== false) this.output.connect(ctx.destination);

    this.node.port.onmessage = (e) => { const d = e.data; if (d && d.type === 'events') this._onEvents(decodeEvents(d.data, d.count)); };
    this.master.port.onmessage = (e) => { if (e.data && e.data.type === 'meter') this.meter = e.data; };
  }

  /** 'running' | 'suspended' | 'closed' (offline contexts report their own state) */
  get state() { return this.ctx.state; }
  get currentTime() { return this.ctx.currentTime; }
  /** seconds between rendering and hearing (base + output latency) */
  get latency() { return (this.ctx.baseLatency || 0) + (this.ctx.outputLatency || 0); }
  /** true while the context still waits for a user gesture */
  get needsGesture() { return !this.offline && this.started && this.ctx.state !== 'running'; }

  /** Start playback. Call from a click/tap/key handler. Resolves with the context state. */
  async start() {
    this.node.port.postMessage({ type: 'run', on: true });
    this.started = true;
    this._ramp(this.volume, 0.05);
    if (!this.offline && this.ctx.state !== 'running') {
      const r = this.ctx.resume().catch(() => {});
      await Promise.race([r, new Promise((res) => setTimeout(res, 300))]); // resume() can stay pending without a gesture
      if (this.ctx.state !== 'running') this._armGesture();
    }
    return this.ctx.state;
  }
  /** Resume a suspended/interrupted context (call from a user gesture). */
  async resume() {
    if (this.offline) return this.ctx.state;
    if (!this.started) return this.start();
    const r = this.ctx.resume().catch(() => {});
    await Promise.race([r, new Promise((res) => setTimeout(res, 300))]);
    if (this.ctx.state !== 'running') this._armGesture();
    return this.ctx.state;
  }
  /** Fade out and pause rendering (suspends the context when this object created it). */
  async stop() {
    if (!this.started) return;
    this.started = false;
    this._ramp(0, 0.06);
    this._disarmGesture();
    if (this.offline) { this.node.port.postMessage({ type: 'run', on: false }); return; }
    await new Promise((res) => setTimeout(res, 250));
    if (this.started) return; // restarted meanwhile
    this.node.port.postMessage({ type: 'run', on: false });
    if (this.owned && this.ctx.state === 'running') await this.ctx.suspend().catch(() => {});
  }
  /** Master volume 0..1 (post-limiter, so it can never cause clipping). */
  setVolume(v) { this.volume = clamp01(+v || 0); if (this.started) this._ramp(this.volume, 0.03); }

  /** Per-frame controls. Missing fields keep their previous value. dhrr is derived from hrr when omitted. */
  update(c = {}) {
    const m = this._ctl;
    m.intensity = c.intensity; m.hrr = c.hrr; m.dhrr = c.dhrr; m.camDist = c.camDist; m.camAz = c.camAz; m.wind = c.wind;
    if (typeof c.hrr === 'number' && typeof c.dhrr !== 'number') {
      const now = performance.now();
      if (this._lastHrr !== null) { const dt = Math.max(1 / 240, (now - this._lastHrrT) / 1000); m.dhrr = Math.max(-20, Math.min(20, (c.hrr - this._lastHrr) / dt)); }
      this._lastHrr = c.hrr; this._lastHrrT = now;
    }
    this.node.port.postMessage(m);
  }
  /**
   * Scripted event: { type, strength 0..1, pan -1..1 (fire-local lateral position), x?, y?, z? (m), screenPan?, time? (context s) }.
   * Returns the AudioContext time at which it sounds.
   */
  trigger(ev = {}) {
    if (!EVENT_TYPES.includes(ev.type) && !['log_shift', 'logShift', 'crackleBurst'].includes(ev.type)) throw new Error('FireAudio.trigger: unknown event type ' + ev.type);
    const when = typeof ev.time === 'number' ? ev.time : this.ctx.currentTime + this.scheduleAhead;
    this.node.port.postMessage({ type: 'event', event: { ...ev, when } });
    return when;
  }
  /**
   * Subscribe to events reported by the audio engine. By default only random pops the engine generated itself,
   * delivered when the sound reaches the speakers. opts: { all: true } include scripted events too;
   * { timing: 'immediate' } deliver on arrival (ev.time = performance.now() timestamp when it will be heard).
   * Returns an unsubscribe function.
   */
  onEvent(cb, opts = {}) { const s = { cb, all: !!opts.all, immediate: opts.timing === 'immediate' }; this._subs.add(s); return () => this._subs.delete(s); }
  /** Advanced: change an engine parameter (e.g. 'popRate', 'fireDiameter', 'mix', 'simCoupling'). */
  setParam(name, value) { this.node.port.postMessage({ type: 'param', name, value }); }
  setMakeupDb(db) { this.master.port.postMessage({ type: 'makeup', db }); } // smoothed over ~30 ms in the master
  /** Release everything (closes the context when this object created it). */
  async dispose() {
    this._disarmGesture();
    this.node.port.postMessage({ type: 'dispose' }); this.master.port.postMessage({ type: 'dispose' });
    try { this.output.disconnect(); this.master.disconnect(); this.reverb.disconnect(); this.node.disconnect(); } catch { /* already */ }
    if (this.owned && !this.offline && this.ctx.state !== 'closed') await this.ctx.close().catch(() => {});
  }

  // ------------------------------------------------------------------ internals
  _ramp(v, tau) {
    const g = this.output.gain, t = this.ctx.currentTime;
    if (this.offline) { g.setValueAtTime(v, t); return; }
    g.cancelScheduledValues(t); g.setValueAtTime(g.value, t); g.setTargetAtTime(v, t, tau / 3);
  }
  _armGesture() {
    if (this._gestureArmed || typeof window === 'undefined') return;
    this._gestureArmed = true;
    for (const t of GESTURES) window.addEventListener(t, this._onGesture, { capture: true, passive: true });
  }
  _disarmGesture() {
    if (!this._gestureArmed) return;
    this._gestureArmed = false;
    for (const t of GESTURES) window.removeEventListener(t, this._onGesture, { capture: true });
  }
  _perfTime(contextTime) {
    if (this.offline) return NaN;
    const ts = this.ctx.getOutputTimestamp ? this.ctx.getOutputTimestamp() : null;
    if (ts && ts.contextTime > 0 && ts.performanceTime > 0) return ts.performanceTime + (contextTime - ts.contextTime) * 1000;
    return performance.now() + (contextTime - this.ctx.currentTime + this.latency) * 1000;
  }
  _onEvents(list) {
    for (const raw of list) {
      const ev = {
        type: raw.type, strength: raw.strength, size: raw.size, pan: raw.pan, x: raw.x, y: raw.y, z: raw.z, stereoPan: raw.stereoPan,
        source: raw.source, id: raw.id >= 0 ? raw.id : undefined, contextTime: raw.contextTime, engineTime: raw.t, time: this._perfTime(raw.contextTime + this.masterDelay),
      };
      this.recentEvents.push(ev); if (this.recentEvents.length > 64) this.recentEvents.shift();
      for (const s of this._subs) {
        if (!s.all && !(ev.source === 'random' && ev.type === 'pop')) continue;
        if (s.immediate || this.offline || !isFinite(ev.time)) { safeCall(s.cb, ev); continue; }
        const d = ev.time - performance.now();
        if (d <= 1) safeCall(s.cb, ev); else setTimeout(() => safeCall(s.cb, ev), d);
      }
    }
  }
}

function clamp01(v) { return v < 0 ? 0 : v > 1 ? 1 : v; }
function safeCall(cb, ev) { try { cb(ev); } catch (e) { console.error('FireAudio onEvent callback failed:', e); } }

export default FireAudio;
